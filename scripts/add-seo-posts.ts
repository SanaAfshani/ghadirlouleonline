async function main() {
  console.log(`دیتابیس: ${new URL(process.env.DATABASE_URL!).host}`);
  console.log(APPLY ? '>>> حالت اعمال\n' : '>>> حالت آزمایشی (بدون تغییر)\n');

  const author = await prisma.user.findFirst({ where: { role: 'ADMIN' }, orderBy: { createdAt: 'asc' }, select: { id: true } });
  if (!author) throw new Error('کاربر ادمین برای نویسنده مقاله پیدا نشد');

  const written: string[] = [];

  for (const { slug, content, tags, faqs, ...rest } of SEO_POSTS) {
    const html = content.trim();
    const data = {
      ...rest,
      content: html,
      tags: JSON.stringify(tags),
      faqs: serializeFaqs(faqs),
      readTime: estimateReadTimeMinutes(html),
      published: true,
    };
    const existing = await prisma.blogPost.findUnique({ where: { slug }, select: { id: true } });
    if (existing && !UPDATE) {
      console.log(`  = موجود /blog/${slug} (بدون تغییر؛ برای بازنویسی --update)`);
      continue;
    }
    console.log(`  ${existing ? '✎ به‌روزرسانی' : '+ ساخت'} /blog/${slug} (${data.readTime} دقیقه مطالعه)`);
    if (APPLY) {
      await prisma.blogPost.upsert({ where: { slug }, update: data, create: { ...data, slug, authorId: author.id } });
      written.push(`/blog/${slug}`);
    }
  }
  if (APPLY) {
    // مثل انتشار از پنل: Bing (و از آن ChatGPT و Copilot) همان روز خبردار می‌شود
    if (written.length) pingIndexNow([...written, '/blog']);
    console.log('\nانجام شد.');
  }
}

