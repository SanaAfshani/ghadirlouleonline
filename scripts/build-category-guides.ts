const GUIDES = [
  { slug: 'corrugated-fittings', content: FITTINGS_CONTENT },
  { slug: 'spiral-pipes', content: SPIRAL_CONTENT },
];

async function main() {
  console.log(`دیتابیس: ${new URL(process.env.DATABASE_URL!).host}`);
  console.log(APPLY ? '>>> حالت اعمال\n' : '>>> حالت آزمایشی (بدون تغییر)\n');

  for (const g of GUIDES) {
    const category = await prisma.category.findUnique({ where: { slug: g.slug }, select: { id: true, content: true } });
    if (!category) {
      console.log(`  ⚠ دسته ${g.slug} پیدا نشد`);
      continue;
    }
    const words = g.content.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
    if (category.content && !FORCE) {
      console.log(`  = ${g.slug}: متن دارد (${category.content.length} نویسه) — برای بازنویسی --force`);
      continue;
    }
    console.log(`  ${category.content ? '✎ بازنویسی' : '+ نوشتن'} ${g.slug}: ${words} کلمه`);
    if (APPLY) await prisma.category.update({ where: { id: category.id }, data: { content: g.content } });
  }
  if (APPLY) console.log('\nانجام شد.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
