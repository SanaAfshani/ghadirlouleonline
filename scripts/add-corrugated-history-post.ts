async function main() {
  console.log(`دیتابیس: ${new URL(process.env.DATABASE_URL!).host}`);
  console.log(APPLY ? '>>> حالت اعمال\n' : '>>> حالت آزمایشی (بدون تغییر)\n');

  const existing = await prisma.blogPost.findUnique({ where: { slug: SLUG }, select: { id: true } });
  console.log(`  ${existing ? '✎ به‌روزرسانی' : '+ ساخت'} /blog/${SLUG} (${post.readTime} دقیقه مطالعه)`);
  if (!APPLY) return;

  const author = await prisma.user.findFirst({ where: { role: 'ADMIN' }, orderBy: { createdAt: 'asc' }, select: { id: true } });
  if (!author) throw new Error('کاربر ادمین برای نویسنده مقاله پیدا نشد');

  await prisma.blogPost.upsert({
    where: { slug: SLUG },
    update: post,
    create: { ...post, slug: SLUG, authorId: author.id },
  });
  console.log('\nانجام شد.');
}

